#!/usr/bin/env python3
"""Build a BPA release into standard/ from the specification (DEC-032, DSN-BPA-001).

Steps:
  1. read the clause catalogue of docs/50-system/30-standard and the release scope
     (standard/release/<version>/scope.json);
  2. write the clauses in scope to standard/spec/<file>.md (never edited by hand);
  3. write a JSON Schema for every DAT-* block named by a clause in scope to
     standard/spec/schemas/;
  4. check every vector in standard/vectors/: canonical JSON, DAT-ConformanceVector members,
     ID inside the VER-CONF range of its first clause, clauses in scope, known operations,
     and replay on the reference oracle;
  5. write the coverage report (MUST clauses with a VER-CONF range that have a vector);
  6. write the manifest of SHA-256 hashes of every released file.
Prints `errors: N`; exits non-zero on errors.

Usage: python3 standard/tools/build_release.py [version]
"""
import hashlib
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from bpa.canon import canonical, content_id    # noqa: E402
from bpa.ops import OPERATIONS, run_vector     # noqa: E402
from bpa.spec import clauses, REPO, STD_DIR    # noqa: E402

STD = os.path.join(REPO, 'standard')
VECTOR_REQUIRED = ('id', 'clauses', 'profile', 'polarity', 'setup', 'steps', 'description')
VECTOR_MEMBERS = set(VECTOR_REQUIRED) | {'determinism', 'tags'}
TYPE_SCHEMA = {
    'text': {'type': 'string'}, 'integer': {'type': ['integer', 'string']}, 'boolean': {'type': 'boolean'},
    'decimal': {'type': 'string', 'pattern': r'^-?(0|[1-9][0-9]*)(\.[0-9]+)?$'},
    'date': {'type': 'string', 'pattern': r'^[0-9]{4}-[0-9]{2}-[0-9]{2}$'},
    'instant': {'type': 'string', 'pattern': r'^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]{6}Z$'},
    'period': {'type': 'object', 'required': ['from', 'to']}, 'list': {'type': 'array'},
    'map': {'type': 'object'}, 'composite': {'type': 'object'}, 'json': {}, 'reference': {'type': 'string'},
    'enum': {'type': 'string'}, 'money': {'type': 'object', 'required': ['amount', 'currency']},
}
FIELD = re.compile(r'^  ([a-z_]+): \{ type: ([a-z_]+), required: (true|false), description: "(.*)" \}$')


def dat_blocks():
    out = {}
    for f in sorted(os.listdir(STD_DIR)):
        if not f.endswith('.md'):
            continue
        text = open(os.path.join(STD_DIR, f), encoding='utf-8').read()
        for block in re.findall(r'```yaml\n(.*?)```', text, re.S):
            name = None
            for line in block.splitlines():
                m = re.match(r'^(DAT-[A-Za-z0-9]+):$', line)
                if m:
                    name = m.group(1)
                    out[name] = []
                    continue
                m = FIELD.match(line)
                if m and name:
                    out[name].append(m.groups())
    return out


def json_schema(name, fields):
    props, req = {}, []
    for member, type_, required, desc in fields:
        p = dict(TYPE_SCHEMA.get(type_, {}))
        values = [v.strip() for v in desc.split('|')]
        if type_ == 'enum' and len(values) > 1 and all(re.fullmatch(r'[a-z0-9_-]+', v) for v in values):
            p['enum'] = values
        p['description'] = desc
        props[member] = p
        if required == 'true':
            req.append(member)
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema', '$id': name, 'title': name,
            'type': 'object', 'properties': props, 'required': req}


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else '0.1'
    rel = os.path.join(STD, 'release', version)
    scope_doc = json.load(open(os.path.join(rel, 'scope.json')))
    cat = clauses()
    scope = ['STD-%s-%s' % (a, n) for a, ns in scope_doc['clauses'].items() for n in ns]
    errors = [('scope', 'unknown clause %s' % c) for c in scope if c not in cat]
    scope = [c for c in scope if c in cat]

    # 2. clauses
    spec_dir = os.path.join(STD, 'spec')
    for f in os.listdir(spec_dir) if os.path.isdir(spec_dir) else []:
        if f.endswith('.md'):
            os.remove(os.path.join(spec_dir, f))
    by_file = {}
    for c in scope:
        by_file.setdefault(cat[c]['file'], []).append(c)
    for f, cs in sorted(by_file.items()):
        src = open(os.path.join(STD_DIR, f), encoding='utf-8').read()
        title = next(l[2:] for l in src.splitlines() if l.startswith('# '))
        body = ['# %s' % title, '',
                '> BPA %s. Generated by `standard/tools/build_release.py` from `docs/50-system/30-standard/%s`;'
                ' do not edit. Clauses outside this release are omitted.' % (scope_doc['version'], f), '']
        body += [cat[c]['block'] for c in cs]
        write(os.path.join(spec_dir, f), '\n'.join(body))

    # 3. schemas
    dats = dat_blocks()
    schema_dir = os.path.join(spec_dir, 'schemas')
    if os.path.isdir(schema_dir):
        for f in os.listdir(schema_dir):
            os.remove(os.path.join(schema_dir, f))
    wanted = sorted({d for c in scope for d in re.findall(r'`(DAT-[A-Za-z0-9]+)`',
                                                           re.search(r'\*\*Grammar / Schema:\*\*(.*)', cat[c]['block']).group(1)
                                                           if re.search(r'\*\*Grammar / Schema:\*\*(.*)', cat[c]['block']) else '')})
    for d in wanted:
        if d not in dats:
            errors.append(('schema', '%s has no YAML block' % d))
            continue
        write(os.path.join(schema_dir, d + '.schema.json'), json.dumps(json_schema(d, dats[d]), indent=2, sort_keys=True) + '\n')

    # 4. vectors
    vec_dir = os.path.join(STD, 'vectors')
    vectors = []
    for prof in sorted(os.listdir(vec_dir)):
        pdir = os.path.join(vec_dir, prof)
        if not os.path.isdir(pdir):
            continue
        for f in sorted(os.listdir(pdir)):
            path = os.path.join(pdir, f)
            raw = open(path, encoding='utf-8').read()
            v = json.loads(raw)
            vectors.append(v)
            where = 'vectors/%s/%s' % (prof, f)
            if raw != canonical(v) + '\n':
                errors.append((where, 'not canonical JSON'))
            missing = [k for k in VECTOR_REQUIRED if k not in v]
            extra = set(v) - VECTOR_MEMBERS
            if missing or extra:
                errors.append((where, 'members missing %s, unknown %s' % (missing, sorted(extra))))
                continue
            if f != v['id'] + '.json' or prof != v['profile'].lower():
                errors.append((where, 'file name or folder does not match id/profile'))
            first = v['clauses'][0]
            for c in v['clauses']:
                if c not in scope:
                    errors.append((where, '%s is not in release %s' % (c, version)))
            rng = cat.get(first, {}).get('range')
            num = int(v['id'].split('-')[-1])
            if not rng or not rng[0] <= num <= rng[1]:
                errors.append((where, 'id outside the VER-CONF range of %s' % first))
            if cat.get(first, {}).get('profile') != v['profile']:
                errors.append((where, 'profile differs from the clause profile'))
            for s in v['setup'] + v['steps']:
                if s['op'] not in OPERATIONS:
                    errors.append((where, 'unknown operation %s' % s['op']))
            for label, problem in run_vector(v):
                errors.append((where, 'replay %s: %s' % (label, problem)))
    ids = [v['id'] for v in vectors]
    if len(set(ids)) != len(ids):
        errors.append(('vectors', 'duplicate ids'))

    # 5. coverage
    covered = {}
    for v in vectors:
        for c in v['clauses']:
            covered.setdefault(c, []).append(v['id'])
    lines = ['# BPA %s — Coverage report' % scope_doc['version'], '',
             '> Generated by `standard/tools/build_release.py`. MET-QUAL-003 counts the MUST clauses of the',
             '> release that have a VER-CONF range; clauses without one (vector format, adapter, runner,',
             '> error registry) are verified by inspection (VER-INSP-9000).', '',
             '| Profile | MUST clauses with a range | Covered | Coverage | Vectors | Prototype vectors |',
             '|---|---|---|---|---|---|']
    total_m = total_c = 0
    for prof in scope_doc['profiles']:
        ms = [c for c in scope if cat[c]['profile'] == prof and cat[c]['must'] and cat[c]['range']]
        cv = [c for c in ms if c in covered]
        nv = [v for v in vectors if v['profile'] == prof]
        npv = [v for v in nv if 'prototype' in v.get('tags', [])]
        total_m += len(ms)
        total_c += len(cv)
        lines.append('| %s | %d | %d | %s | %d | %d |' % (prof, len(ms), len(cv),
                                                       '%.0f%%' % (100.0 * len(cv) / len(ms)) if ms else '—', len(nv), len(npv)))
    pct = 100.0 * total_c / total_m if total_m else 0
    lines.append('| **All** | **%d** | **%d** | **%.0f%%** | **%d** | **%d** |' % (
        total_m, total_c, pct, len(vectors), sum(1 for v in vectors if 'prototype' in v.get('tags', []))))
    lines += ['', '## Clauses', '', '| Clause | Profile | MUST | Vectors |', '|---|---|---|---|']
    for c in scope:
        ids_ = covered.get(c, [])
        rng = 'no range' if not cat[c]['range'] else (
            '%d (%s…%s)' % (len(ids_), ids_[0], ids_[-1]) if ids_ else '**none**')
        lines.append('| %s | %s | %s | %s |' % (c, cat[c]['profile'], 'yes' if cat[c]['must'] else 'no', rng))
    write(os.path.join(rel, 'coverage.md'), '\n'.join(lines) + '\n')

    # 6. manifest
    files = []
    for root in ('spec', 'vectors'):
        for dirpath, _, names in os.walk(os.path.join(STD, root)):
            for n in sorted(names):
                if n == '.gitkeep':
                    continue
                p = os.path.join(dirpath, n)
                files.append({'path': os.path.relpath(p, STD).replace(os.sep, '/'),
                              'sha256': hashlib.sha256(open(p, 'rb').read()).hexdigest()})
    for n in ('scope.json', 'coverage.md'):
        p = os.path.join(rel, n)
        files.append({'path': os.path.relpath(p, STD).replace(os.sep, '/'),
                      'sha256': hashlib.sha256(open(p, 'rb').read()).hexdigest()})
    files.sort(key=lambda x: x['path'])
    manifest = {'standard': 'BPA', 'version': scope_doc['version'], 'profiles': scope_doc['profiles'],
                'clauses': len(scope), 'vectors': len(vectors), 'files': files}
    manifest['content_id'] = content_id('ubos.pack.v1', {k: manifest[k] for k in ('standard', 'version', 'files')})
    write(os.path.join(rel, 'manifest.json'), json.dumps(manifest, indent=2, sort_keys=True) + '\n')

    print('BPA %s: clauses %d, schemas %d, vectors %d, MUST coverage %d/%d (%.0f%%)' % (
        scope_doc['version'], len(scope), len(wanted), len(vectors), total_c, total_m, pct))
    for where, msg in errors:
        print('ERROR', where, msg)
    print('errors: %d' % len(errors))
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
