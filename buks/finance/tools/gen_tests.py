"""Generate the tie-out tests of the finance Buk (PH-2 step 9, DEC-141).

Reads the frozen sample company of the US Basic Finance requirements
(`docs/finance-requirements/sample-company/*.csv`) and its expected results
(`docs/finance-requirements/21-expected-results.md`), and writes `tests/sample-*.yaml`:
scenario tests that load the sample company through adapter operations and compare
the Buk's results with the expected figures. The generated files are never edited by hand.

Usage: python3 buks/finance/tools/gen_tests.py [--check]
"""
