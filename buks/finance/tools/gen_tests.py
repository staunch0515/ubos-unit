CONTROLLER = 'did:ubos:acme:01900000-0000-7000-8000-0000000000e2'


def chart_changes():
    out = []
    for r in rows('chart-of-accounts.csv'):
        t = TYPES.get(r['type']) or ('income' if r['normal_balance'] == 'C' else 'expense')
        out.append({'op': 'create', 'class': 'GlAccount', 'object_id': uid('account', r['code']),
                    'slug': r['code'], 'valid': {'from': '2025-01-01'},
                    'body': {'number': r['code'], 'name': r['name'], 'type': t, 'category': r['type'],
                             'normal_balance': r['normal_balance'], 'statement_line': r['statement_line']}})
        if r['code'] in CONTROL:
            out[-1]['body']['control'] = CONTROL[r['code']]
    return out


def period_changes():
    """The monthly periods of December 2025 to January 2027 (FIN-PC-001)."""
    out = []
    months = [(2025, 12)] + [(2026, m) for m in range(1, 13)] + [(2027, 1)]
    for y, m in months:
        slug = '%d-%02d' % (y, m)
        ny, nm = (y + 1, 1) if m == 12 else (y, m + 1)
        out.append({'op': 'create', 'class': 'FiscalPeriod', 'object_id': uid('period', slug), 'slug': slug,
                    'valid': {'from': '2025-01-01'},
                    'body': {'start': '%d-%02d-01' % (y, m), 'end': '%d-%02d-01' % (ny, nm), 'state': 'open',
                             'fiscal_year': str(y), 'number': m}})
    return out


def opening_changes():
    out = []
    for n, r in enumerate(rows('opening-balances.csv')):
        c = cents(r['debit']) - cents(r['credit'])
        doc = 'OB-' + r['date']
        out.append({'op': 'append', 'class': 'JournalLine', 'entry_id': uid('line', doc, n),
                    'ledger_key': {'account': account_uri(r['account'])}, 'posting_group': doc,
                    'valid_at': r['date'],
                    'body': {'account': account_uri(r['account']), 'amount': money(amount(c)),
                             'document': doc, 'kind': 'opening', 'description': 'Opening balance',
                             'date': r['date'], 'side': 'credit' if c < 0 else 'debit'}})
    return out


def documents(month):
    """The documents of `transactions.csv` whose posting date is in a month, in file order:
    (document, kind, posting_date, recorded_on, lines)."""
    out = {}
    for r in rows('transactions.csv'):
        if not r['posting_date'].startswith(month):
            continue
        d = out.setdefault(r['document'], (r['document'], r['kind'], r['posting_date'], r['recorded_on'], []))
        d[4].append(r)
    return list(out.values())


def document_changes(doc):
    name, kind, posting, _, lines = doc
    out = []
    for n, r in enumerate(lines):
        c = cents(r['debit']) - cents(r['credit'])
        body = {'account': account_uri(r['account']), 'amount': money(amount(c)), 'document': name,
                'kind': kind, 'description': r['description'], 'date': posting,
                'side': 'credit' if c < 0 else 'debit'}
        if r['party']:
            body['party'] = r['party']
        out.append({'op': 'append', 'class': 'JournalLine', 'entry_id': uid('line', name, n),
                    'ledger_key': {'account': account_uri(r['account'])}, 'posting_group': name,
                    'valid_at': posting, 'body': body})
    return out


START = datetime.datetime(2026, 1, 1)


def advance(clock, at):
    """The step moving the clock to `at`, if later."""
    if at > clock:
        return [{'advance': '%dm' % ((at - clock).total_seconds() // 60)}], at
    return [], clock


def posting_steps(month, clock, events=()):
    """Each document of a month committed at noon of its recording date, in recording order,
    with `events` ((instant, steps)) placed by time; returns the steps and the clock after."""
    items = [(datetime.datetime.fromisoformat(d[3]) + datetime.timedelta(hours=12), n, d)
             for n, d in enumerate(documents(month))]
    items += [(at, -1, s) for at, s in events]
    steps = []
    for at, n, item in sorted(items, key=lambda x: (x[0], x[1])):
        more, clock = advance(clock, at)
        steps += more
        if n < 0:
            steps += item
        else:
            steps.append({'op': 'commit', 'input': {'branch': BRANCH, 'changes': document_changes(item)}})
    return steps, clock


def close_steps(slug, tb):
    """Close a period (STD-KIND-025, -026): to closing, then close_period, whose artefact
    holds the balances of the trial balance `tb`."""
    oid = uid('period', slug)
    balances = [{'class': 'JournalLine', 'ledger_key': g['key'],
                 'amounts': {'amount': g['values']['balance']}} for g in balance_groups(tb)]
    return [
        {'op': 'read', 'input': {'branch': BRANCH, 'object_id': oid}, 'label': 'period-' + slug},
        {'op': 'commit', 'input': {'branch': BRANCH, 'changes': [
            {'op': 'update', 'object_id': oid, 'base': {'$ref': 'period-%s/version_hash' % slug},
             'body': {'state': 'closing'}}]}},
        {'op': 'close_period',
         'input': {'branch': BRANCH, 'period': oid, 'artefact_id': uid('artefact', slug)},
         'expect': {'match': 'subset', 'result': {'tag': 'close-%s-1' % slug, 'balances': balances}}},
    ]


def account_reads(asof, figures, tx_time=None):
    """One read of `gl-balance` per account: {code: cents}."""
    out = []
    for code, c in figures.items():
        i = {'branch': BRANCH, 'projection': 'gl-balance', 'asof': asof,
             'group': {'account': account_uri(code)}}
        if tx_time:
            i['tx_time'] = tx_time
        values = {'balance': [money(amount(c))]}
        out.append({'op': 'read_projection', 'input': i,
                    'expect': {'match': 'subset', 'result': {'groups': [
                        {'key': {'account': account_uri(code)}, 'values': values}]}}})
    return out


def posted_lines(fid):
    """{(account, document): cents} of a postings section ("6200 8,500.00; 2000 (8,500.00)")."""
    out = {}
    for cells in section(fid):
        doc = cells[1]
        for part in cells[4].split(';'):
            code, _, value = part.strip().partition(' ')
            key = (code, doc)
            out[key] = out.get(key, 0) + cents(value)
    return out


def document_groups(lines):
    """The groups of `gl-document`, in canonical key order."""
    groups = [{'key': {'account': account_uri(code), 'document': doc},
               'values': {'amount': [money(amount(c))]}} for (code, doc), c in lines.items()]
    groups.sort(key=lambda g: json.dumps(g['key'], sort_keys=True, separators=(',', ':')))
    return groups


def opening_lines():
    return {(code, 'OB-2025-12-31'): c for code, c in trial_balance('FIN-EXP-01').items() if c}


def trial_balance(fid):
    """{account code: balance in cents} of a trial-balance section."""
    out = {}
    for cells in section(fid):
        if not cells[0] or not cells[0].isdigit():
            continue
        out[cells[0]] = cents(cells[2]) - cents(cells[3])
    return out


def balance_groups(tb):
    """The groups of `gl-balance` for a trial balance, in canonical key order."""
    groups = []
    for code, c in tb.items():
        if c == 0:
            continue
        groups.append({'key': {'account': account_uri(code)},
                       'values': {'balance': [money(amount(c))]}})
    groups.sort(key=lambda g: json.dumps(g['key'], sort_keys=True, separators=(',', ':')))
    return groups


