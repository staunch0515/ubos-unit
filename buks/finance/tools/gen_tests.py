def on(branch, steps):
    """The steps with their branch replaced."""
    out = json.loads(json.dumps(steps))
    for s in out:
        if isinstance(s.get('input'), dict) and s['input'].get('branch') == BRANCH:
            s['input']['branch'] = branch
    return out


