#!/usr/bin/env python3
"""Write the tie-out report of the finance Buk (PH-2 steps 9e and 10h, DEC-145, DEC-156): run `forge test` in
memory and on PostgreSQL and record, per test, the expected-results sections it ties out, the
figures it compares and the outcome on each backend, in `docs/tie-out.md` (generated; never
edited by hand).

Usage: python3 buks/finance/tools/tieout_report.py --forge target/release/forge \
           --database "host=127.0.0.1 user=postgres dbname=bpa"
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
BUK = os.path.dirname(HERE)


def figures(test):
    """The number of figures a test compares: groups, statement lines (columns count each
    value), report rows, the other members of a port's result and expected errors."""
    n = 0
    steps = test.get('steps', [])
    if test.get('kind') == 'port':
        steps = [{'expect': {'result': {'result': test['expect']['result']}}}]
    for s in steps:
        exp = s.get('expect') or {}
        if 'error_code' in exp:
            n += 1
        res = (exp.get('result') or {})
        res = res.get('result', res) if isinstance(res, dict) else {}
        if not isinstance(res, dict):
            n += 1
            continue
        for k, v in res.items():
            if k in ('groups', 'balances'):
                n += len(v)
            elif k == 'lines' and isinstance(v, list):
                for line in v:
                    n += len([x for x in line.get('values', []) if x is not None]) if 'values' in line else 1
            elif isinstance(v, list):
                n += len(v)
            elif isinstance(v, dict):
                n += len(v)
            else:
                n += 1
    return n


def run(forge, extra):
    with tempfile.TemporaryDirectory() as d:
        report = os.path.join(d, 'r.json')
        p = subprocess.run([forge, 'test', BUK, '--report', report] + extra, capture_output=True, text=True)
        if not os.path.exists(report):
            raise SystemExit('forge test failed: %s' % (p.stderr or p.stdout)[-2000:])
        return {r['name']: r for r in json.load(open(report))['results']}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--forge', default='target/release/forge')
    ap.add_argument('--database', required=True)
    a = ap.parse_args()
    mem = run(a.forge, [])
    pg = run(a.forge, ['--backend', 'postgres', '--database', a.database])
    rows = []
    total = 0
    for f in sorted(os.listdir(os.path.join(BUK, 'tests'))):
        text = open(os.path.join(BUK, 'tests', f), encoding='utf-8').read()
        data = json.loads(text[text.index('{'):])
        for t in data['tests']:
            n = figures(t)
            total += n
            ids = ', '.join(sorted(set(re.findall(r'(?:FIN-[A-Z]+-\d+|SCN-5\d\d)', t['name'])))) or '—'
            res = lambda r: (r or {}).get('outcome', (r or {}).get('result', 'missing'))
            rows.append('| `%s` | %s | %s | %d | %s | %s |' % (f, t['name'], ids, n, res(mem.get(t['name'])),
                                                               res(pg.get(t['name']))))
    ok = all(r.endswith('| pass | pass |') for r in rows)
    out = ['# Tie-out report — finance Buk, PH-2 steps 9 and 10', '',
           '> Generated by `tools/tieout_report.py` on %s from `forge test` in memory and on PostgreSQL.'
           % datetime.date.today().isoformat(), '> Do not edit by hand.', '',
           'The tests compare the Buk\'s results with `docs/finance-requirements/21-expected-results.md` '
           '(fin-req-v1.0) and with the acceptance criteria of the requirements they name. Every figure must be '
           'equal; lists must match in length and order. "Ties out" lists the requirement, expected-result and '
           'scenario IDs a test names.', '',
           '| File | Test | Ties out | Figures | Memory | PostgreSQL |', '|---|---|---|---|---|---|'] + rows + [
           '', '**%d tests, %d figures compared, %s.**' % (len(rows), total,
                                                         'all pass on both backends' if ok else 'NOT ALL PASS')]
    os.makedirs(os.path.join(BUK, 'docs'), exist_ok=True)
    with open(os.path.join(BUK, 'docs', 'tie-out.md'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out) + '\n')
    print('tie-out: %d tests, %d figures, %s' % (len(rows), total, 'pass' if ok else 'FAIL'))


if __name__ == '__main__':
    main()
