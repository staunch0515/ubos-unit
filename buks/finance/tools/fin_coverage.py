#!/usr/bin/env python3
"""The coverage of the US Basic Finance requirements by the finance Buk (PH-2 step 10g-3, DEC-155).

Reads the requirements of `docs/finance-requirements/` (fin-req-v1.0), the names of the Buk's
tests and `tools/fin-status.txt`, checks them, and writes `docs/fin-coverage.md` (generated;
never edited by hand):

- a requirement whose ID a test name carries is "tested";
- every other requirement has exactly one line in fin-status.txt with a known status;
- a "covered" line names fragments of test names, each of which must occur in a test name;
- a status line for an ID that no requirement has, or for a tested ID, is an error.

Usage: python3 buks/finance/tools/fin_coverage.py [--check] [--closing]
  --check    fail when docs/fin-coverage.md is stale
  --closing  also fail when a Must requirement is still "gap" (the exit of step 10)
"""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUK = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(BUK))
FIN = os.path.join(ROOT, 'docs', 'finance-requirements')
STATUSES = ('tested', 'covered', 'platform', 'assigned', 'gap')
REQ = re.compile(r'^### (FIN-[A-Z]+-\d+) — (.*)\n- \*\*Requirement:\*\* .*\n- \*\*Priority:\*\* (\w+)', re.M)


def requirements():
    out = {}
    for path in sorted(glob.glob(os.path.join(FIN, '[01][0-9]-*.md'))):
        name = os.path.basename(path)
        if name.startswith(('00-', '01-')):
            continue          # conventions and scope: no requirements, only examples
        for m in REQ.finditer(open(path, encoding='utf-8').read()):
            out[m.group(1)] = {'title': m.group(2), 'priority': m.group(3), 'file': name}
    return out


def test_names():
    names = []
    for path in sorted(glob.glob(os.path.join(BUK, 'tests', '*.yaml'))):
        text = open(path, encoding='utf-8').read()
        for t in json.loads(text[text.index('{'):])['tests']:
            names.append((os.path.basename(path), t['name']))
    return names


def status_lines(errors):
    out = {}
    for n, line in enumerate(open(os.path.join(HERE, 'fin-status.txt'), encoding='utf-8'), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = [p.strip() for p in line.split('|')]
        if len(parts) != 4:
            errors.append('fin-status.txt:%d: four fields expected' % n)
            continue
        fid, status, evidence, note = parts
        if status not in STATUSES[1:]:
            errors.append('fin-status.txt:%d: unknown status %s' % (n, status))
        if fid in out:
            errors.append('fin-status.txt:%d: %s twice' % (n, fid))
        out[fid] = {'status': status, 'evidence': evidence, 'note': note}
    return out


def main():
    errors = []
    reqs = requirements()
    names = test_names()
    lines = status_lines(errors)
    rows = []
    for fid, r in reqs.items():
        tests = [n for f, n in names if re.search(r'\b%s\b' % re.escape(fid), n)]
        if tests:
            if fid in lines:
                errors.append('%s is tested; remove its line from fin-status.txt' % fid)
            rows.append((fid, r, 'tested', '; '.join(t[:90] for t in tests[:3]) + (' …' if len(tests) > 3 else ''), ''))
            continue
        s = lines.get(fid)
        if s is None:
            errors.append('%s (%s) has no status' % (fid, r['priority']))
            continue
        if s['status'] == 'covered':
            for frag in [x.strip() for x in s['evidence'].split(';') if x.strip()]:
                if not any(frag in n for f, n in names):
                    errors.append('%s: no test name contains "%s"' % (fid, frag))
        rows.append((fid, r, s['status'], s['evidence'], s['note']))
    for fid in lines:
        if fid not in reqs:
            errors.append('fin-status.txt names %s, which is no requirement' % fid)
    count = {}
    for fid, r, st, _, _ in rows:
        count[(r['priority'], st)] = count.get((r['priority'], st), 0) + 1
    prios = ('Must', 'Should', 'Could')
    out = ['# Coverage of the finance requirements — finance Buk', '',
           '> Generated by `tools/fin_coverage.py` from `docs/finance-requirements/` (fin-req-v1.0), the test names '
           'and `tools/fin-status.txt`. Do not edit by hand.', '',
           '| Priority | ' + ' | '.join(STATUSES) + ' | Total |', '|---|' + '---|' * (len(STATUSES) + 1)]
    for p in prios:
        cells = [count.get((p, s), 0) for s in STATUSES]
        out.append('| %s | %s | %d |' % (p, ' | '.join(str(c) for c in cells), sum(cells)))
    out += ['', 'Statuses: *tested* — a test name carries the ID; *covered* — implemented and exercised by the named '
            'tests; *platform* — met by the kernel or platform; *assigned* — a later step; *gap* — to be built in '
            'step 10g-3.', '', '| ID | Requirement | Priority | Status | Evidence | Note |', '|---|---|---|---|---|---|']
    for fid, r, st, ev, note in rows:
        out.append('| %s | %s | %s | %s | %s | %s |' % (fid, r['title'], r['priority'], st,
                                                       ev.replace('|', '/'), note.replace('|', '/')))
    text = '\n'.join(out) + '\n'
    target = os.path.join(BUK, 'docs', 'fin-coverage.md')
    gaps = [fid for fid, r, st, _, _ in rows if st == 'gap' and r['priority'] == 'Must']
    if '--closing' in sys.argv and gaps:
        errors.append('Must requirements still gap: ' + ', '.join(gaps))
    if '--check' in sys.argv:
        old = open(target, encoding='utf-8').read() if os.path.exists(target) else None
        if old != text:
            errors.append('docs/fin-coverage.md is stale (run buks/finance/tools/fin_coverage.py)')
    else:
        with open(target, 'w', encoding='utf-8') as fh:
            fh.write(text)
    for e in errors:
        print('error: ' + e)
    summary = ', '.join('%s %d' % (s, sum(count.get((p, s), 0) for p in prios)) for s in STATUSES)
    print('finance coverage: %d requirements (%s); Must gaps %d; errors: %d' % (len(rows), summary, len(gaps), len(errors)))
    sys.exit(1 if errors else 0)


if __name__ == '__main__':
    main()
