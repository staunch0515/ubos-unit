#!/usr/bin/env python3
"""Generate the SDK error registry from the BPA error registry (DSN-SDK-007, STD-ERR-002).

Reads the table of STD-ERR-002 in standard/spec/17-errors.md and writes the registry of
the Rust SDK (crates/ubos-sdk/src/registry.rs) and of the TypeScript SDK
(packages/sdk-ts/src/registry.ts with the data, packages/sdk-ts/src/codes.ts with one error
class per code). `--check` fails when a written file is out of date (CI).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SPEC = ROOT / "standard/spec/17-errors.md"
RUST = ROOT / "crates/ubos-sdk/src/registry.rs"
TS_DATA = ROOT / "packages/sdk-ts/src/registry.ts"
TS_CODES = ROOT / "packages/sdk-ts/src/codes.ts"


def codes():
    text = SPEC.read_text()
    start = text.index("### STD-ERR-002")
    end = text.index("\n### ", start + 10) if "\n### " in text[start + 10:] else len(text)
    out = []
    for line in text[start:end].splitlines():
        m = re.match(r"\s*\| `([A-Z]+\.[A-Z_]+)` \| (.*?) \| (yes|no) \| (yes|no) \| (\d{3}) \|", line)
        if m:
            out.append((m[1], m[2].strip(), m[3] == "yes", m[4] == "yes", int(m[5])))
    if not out:
        sys.exit("no codes found in STD-ERR-002")
    return out


def variant(code):
    area, name = code.split(".")
    return area.capitalize() + "".join(p.capitalize() for p in name.split("_"))


def rust(cs):
    areas = sorted({c[0].split(".")[0] for c in cs})
    lines = [
        "//! The error registry (STD-ERR-002) as Rust types (DSN-SDK-007).",
        "//!",
        "//! Generated by `crates/ubos-sdk/tools/gen_registry.py` from `standard/spec/17-errors.md`;",
        "//! do not edit.",
        "",
        "/// The module (area) of an error code.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
        "pub enum Area {",
    ]
    for a in areas:
        lines.append(f"    /// `{a}`.")
        lines.append(f"    {a.capitalize()},")
    lines += ["}", "", "/// A registered error code.", "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]", "pub enum Code {"]
    for c, cond, *_ in cs:
        lines.append(f"    /// `{c}`: {cond.replace('`', '')}.")
        lines.append(f"    {variant(c)},")
    lines += ["}", "", "/// `(code, area, retryable, catchable, HTTP status)` of every registered code.",
              "pub const REGISTRY: &[(Code, &str, Area, bool, bool, u16)] = &["]
    for c, _, r, k, h in cs:
        lines.append(f'    (Code::{variant(c)}, "{c}", Area::{c.split(".")[0].capitalize()}, {str(r).lower()}, {str(k).lower()}, {h}),')
    lines += ["];", ""]
    return "\n".join(lines)


def ts(cs):
    areas = sorted({c[0].split(".")[0] for c in cs})
    lines = [
        "// The error registry (STD-ERR-002) of the TypeScript SDK (DSN-SDK-007).",
        "// Generated by crates/ubos-sdk/tools/gen_registry.py from standard/spec/17-errors.md; do not edit.",
        "",
        "/** The module (area) of an error code. */",
        "export type Area =",
    ]
    lines += [f'  | "{a}"' for a in areas]
    lines[-1] += ";"
    lines += ["", "/** A registered error code. */", "export type Code ="]
    lines += [f'  | "{c}"' for c, *_ in cs]
    lines[-1] += ";"
    lines += ["", "/** `[retryable, catchable, HTTP status]` of every registered code. */",
              "export const REGISTRY: Readonly<Record<Code, readonly [boolean, boolean, number]>> = {"]
    for c, _, r, k, h in cs:
        lines.append(f'  "{c}": [{str(r).lower()}, {str(k).lower()}, {h}],')
    lines += ["};", ""]
    return "\n".join(lines)


def ts_codes(cs):
    lines = [
        "// One error class per registered code (STD-ERR-002, DSN-SDK-007): `instanceof VerMergeConflict`.",
        "// Generated by crates/ubos-sdk/tools/gen_registry.py from standard/spec/17-errors.md; do not edit.",
        "",
        'import { UbosError } from "./error.js";',
        "",
    ]
    for c, cond, *_ in cs:
        cond = cond.replace("*/", "* /")
        lines += [f"/** `{c}`: {cond}. */",
                  f"export class {variant(c)} extends UbosError {{",
                  f'  static override readonly code = "{c}";',
                  "}"]
    lines += ["", "/** The class of every registered code. */",
              "export const CLASSES: Readonly<Record<string, typeof UbosError>> = {"]
    lines += [f'  "{c}": {variant(c)},' for c, *_ in cs]
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    # the Rust text as rustfmt writes it, so that `cargo fmt` keeps the file as generated
    formatted = subprocess.run(["rustfmt", "--edition", "2024"], input=rust(codes()),
                               capture_output=True, text=True, check=True).stdout
    outputs = [(RUST, formatted), (TS_DATA, ts(codes())), (TS_CODES, ts_codes(codes()))]
    stale = []
    for path, text in outputs:
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        sys.exit("out of date (run crates/ubos-sdk/tools/gen_registry.py): " + ", ".join(stale))
    print(f"{len(codes())} codes")


if __name__ == "__main__":
    main()
