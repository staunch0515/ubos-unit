//! `forge types` (DSN-FRG-102, DSN-SDK-012): the typed API of a project for the TypeScript
//! and Rust SDKs, versioned per branch and model hash (FR-DEV-031, -032).
//!
//! For every class: its body type (a TypeScript interface extending the parent's, a Rust
//! struct with every field), the union of the class and its subclasses for polymorphic
//! results (a TypeScript discriminated union narrowed on `class`, a Rust enum), typed
//! reads, a query builder compiling to DAT-Query, and one typed method per port. The
//! generated code builds on the typed layer of the SDKs (`@ubos/sdk`, `ubos_sdk::typed`).

use crate::project::Project;
use serde_json::Value;
use std::collections::BTreeMap;

/// A field type of the model mapped to the target languages.
fn map_type(t: &str, lang: &str, custom: &BTreeMap<String, Value>) -> String {
    let ts = lang == "ts";
    match t {
        "text" | "enum" | "date" | "instant" | "uuid" | "uri" | "did" => {
            if ts { "string" } else { "String" }.into()
        }
        "integer" => if ts { "number" } else { "i64" }.into(),
        "decimal" => if ts { "string" } else { "String" }.into(),
        "boolean" => if ts { "boolean" } else { "bool" }.into(),
        "money" => "Money".into(),
        "period" => "Period".into(),
        "blob" => if ts { "BlobRef" } else { "ubos_sdk::BlobRef" }.into(),
        "reference" | "relationship" => if ts { "string" } else { "String" }.into(),
        "list" => if ts {
            "unknown[]"
        } else {
            "Vec<serde_json::Value>"
        }
        .into(),
        "map" | "json" => if ts {
            "Record<string, unknown>"
        } else {
            "serde_json::Value"
        }
        .into(),
        other if custom.contains_key(other) => {
            let base = custom[other]
                .get("base")
                .and_then(Value::as_str)
                .unwrap_or("text");
            map_type(base, lang, &BTreeMap::new())
        }
        _ => if ts { "unknown" } else { "serde_json::Value" }.into(),
    }
}

fn ident(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn", "else", "enum",
    "extern", "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "try", "type",
    "unsafe", "use", "where", "while", "yield",
];

/// A Rust field or parameter name: sanitized, raw when a keyword.
fn rs_ident(name: &str) -> String {
    let i = ident(name);
    if RUST_KEYWORDS.contains(&i.as_str()) {
        format!("r#{i}")
    } else {
        i
    }
}

/// `rename_customer` → `RenameCustomer`.
fn pascal(name: &str) -> String {
    ident(name)
        .split('_')
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// Generate `types.ts` and `types.rs` with the TypeScript SDK imported as `@ubos/sdk`.
pub fn generate(project: &Project) -> Result<(String, String, Value), ubos_dvm::BpaError> {
    generate_with(project, "@ubos/sdk")
}

/// Generate `types.ts` and `types.rs`; `sdk` is the module the TypeScript imports the SDK
/// from. Returns `(typescript, rust, header)`.
pub fn generate_with(
    project: &Project,
    sdk: &str,
) -> Result<(String, String, Value), ubos_dvm::BpaError> {
    let base = ubos_dvm::expressions::registry();
    let decls = project.declarations();
    let vts = project.value_type_decls();
    let reg = base.load(&decls, if vts.is_empty() { None } else { Some(&vts) })?;
    let custom: BTreeMap<String, Value> = reg.value_types().clone();
    let model_hash = project.model_hash()?;
    let branch = &project.manifest.branch;
    let header = serde_json::json!({"project": project.manifest.name, "branch": branch,
        "model_hash": model_hash, "abi": project.manifest.abi});
    let banner = format!(
        "generated by forge types; project {} branch {branch} model {model_hash}; do not edit",
        project.manifest.name
    );
    let mut ts = format!(
        "// {banner}\n\nimport {{ type BlobRef, type CallOptions, type Client, type MutateResult, Query, type Selectors, type Typed, getTyped }} from \"{sdk}\";\n\nexport interface Money {{ amount: string; currency: string }}\nexport interface Period {{ from: string; to: string | null }}\nexport const MODEL_HASH = \"{model_hash}\";\nexport const BRANCH = \"{branch}\";\n\n"
    );
    let mut rs = format!(
        "//! {banner}\n#![allow(missing_docs, dead_code, unused_imports, clippy::all)]\n\nuse serde::{{Deserialize, Serialize}};\nuse ubos_sdk::{{CallOptions, Client, Item, MutateResult, Query, Result, Selectors, Typed}};\n\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct Money {{ pub amount: String, pub currency: String }}\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct Period {{ pub from: String, pub to: Option<String> }}\npub const MODEL_HASH: &str = \"{model_hash}\";\npub const BRANCH: &str = \"{branch}\";\n\n"
    );
    // a blob-typed value type maps to BlobRef only through its base; keep the imports used
    ts.push_str("export type { BlobRef };\n\n");
    for (name, vt) in &custom {
        let base_t = vt.get("base").and_then(Value::as_str).unwrap_or("text");
        ts.push_str(&format!(
            "export type {} = {};\n",
            ident(name),
            map_type(base_t, "ts", &BTreeMap::new())
        ));
        rs.push_str(&format!(
            "pub type {} = {};\n",
            ident(name),
            map_type(base_t, "rs", &BTreeMap::new())
        ));
    }
    if !custom.is_empty() {
        ts.push('\n');
        rs.push('\n');
    }
    let mut names: Vec<String> = decls
        .iter()
        .filter_map(|d| d.get("name").and_then(Value::as_str).map(str::to_string))
        .collect();
    names.sort();
    for name in &names {
        let c = reg.class(name)?;
        let id = ident(name);
        let parent = c.linearization.get(1).cloned();
        // the class and its subclasses in the project, the class first
        let mut family = vec![name.clone()];
        for other in &names {
            if other != name && reg.class(other)?.linearization.contains(name) {
                family.push(other.clone());
            }
        }
        // ---- TypeScript ----
        ts.push_str(&format!(
            "/** class {name} (kind {}, version {}) */\nexport interface {id}{} {{\n",
            c.kind.clone().unwrap_or_default(),
            c.class_version,
            parent
                .as_ref()
                .filter(|p| names.contains(p))
                .map(|p| format!(" extends {}", ident(p)))
                .unwrap_or_default()
        ));
        let own: Vec<&String> = if let Some(p) = parent.as_ref().filter(|p| names.contains(p)) {
            let pc = reg.class(p)?;
            c.fields
                .keys()
                .filter(|k| !pc.fields.contains_key(*k))
                .collect()
        } else {
            c.fields.keys().collect()
        };
        for (fname, decl) in &c.fields {
            if !own.contains(&fname) {
                continue;
            }
            let t = decl.get("type").and_then(Value::as_str).unwrap_or("text");
            let required = decl.get("required") == Some(&Value::Bool(true));
            ts.push_str(&format!(
                "  {}{}: {};\n",
                ident(fname),
                if required { "" } else { "?" },
                map_type(t, "ts", &custom)
            ));
        }
        ts.push_str("}\n");
        ts.push_str(&format!(
            "/** {name} or a subclass: narrow on `class`. */\nexport type {id}Item =\n{};\n",
            family
                .iter()
                .map(|f| format!("  | Typed<\"{f}\", {}>", ident(f)))
                .collect::<Vec<_>>()
                .join("\n")
        ));
        let mut ports_ts = String::new();
        for (pname, port) in &c.ports {
            let params: Vec<&Value> = port.decl["params"]
                .as_array()
                .into_iter()
                .flatten()
                .collect();
            let pt = format!("{id}{}Params", pascal(pname));
            if params.is_empty() {
                ts.push_str(&format!("/** the parameters of {name}.{pname}: none */\nexport type {pt} = Record<string, never>;\n"));
            } else {
                ts.push_str(&format!(
                    "/** the parameters of {name}.{pname} */\nexport interface {pt} {{\n"
                ));
            }
            for p in &params {
                let required = p.get("required") == Some(&Value::Bool(true));
                ts.push_str(&format!(
                    "  {}{}: {};\n",
                    ident(p.get("name").and_then(Value::as_str).unwrap_or("arg")),
                    if required { "" } else { "?" },
                    map_type(
                        p.get("type").and_then(Value::as_str).unwrap_or("text"),
                        "ts",
                        &custom
                    )
                ));
            }
            if !params.is_empty() {
                ts.push_str("}\n");
            }
            ports_ts.push_str(&format!(
                "    /** {} port, declared by {} */\n    {}: (c: Client, target: string, params: {pt}{}, o?: CallOptions): Promise<MutateResult> =>\n      c.invoke(target, \"{pname}\", {{ ...params }}, o),\n",
                port.decl.get("kind").and_then(Value::as_str).unwrap_or("command"),
                port.declared_by,
                ident(pname),
                if params.is_empty() { " = {}" } else { "" }
            ));
        }
        ts.push_str(&format!(
            "/** class {name}: typed reads, queries and ports. */\nexport const {id} = {{\n  name: \"{name}\" as const,\n  /** One object by slug: {name} or a subclass. */\n  get: (c: Client, slug: string, sel?: Selectors): Promise<{id}Item> => getTyped<{id}Item>(c, \"{name}\", slug, sel),\n  /** A query of {name} and its subclasses, compiling to DAT-Query. */\n  query: (): Query<{id}Item, {id}> => new Query<{id}Item, {id}>({{ from: \"{name}\" }}),\n  ports: {{\n{ports_ts}  }},\n}};\n\n"
        ));
        // ---- Rust ----
        rs.push_str(&format!(
            "/// class {name} (kind {}, version {})\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct {id} {{\n",
            c.kind.clone().unwrap_or_default(),
            c.class_version
        ));
        for (fname, decl) in &c.fields {
            let t = decl.get("type").and_then(Value::as_str).unwrap_or("text");
            let required = decl.get("required") == Some(&Value::Bool(true));
            let rt = map_type(t, "rs", &custom);
            if ident(fname) != *fname {
                rs.push_str(&format!("    #[serde(rename = \"{fname}\")]\n"));
            }
            if !required {
                rs.push_str("    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n");
            }
            rs.push_str(&format!(
                "    pub {}: {},\n",
                rs_ident(fname),
                if required {
                    rt
                } else {
                    format!("Option<{rt}>")
                }
            ));
        }
        rs.push_str("}\n");
        rs.push_str(&format!(
            "/// {name} or a subclass.\n#[derive(Debug, Clone)]\npub enum {id}Any {{\n{}}}\n",
            family
                .iter()
                .map(|f| format!("    {}(Typed<{}>),\n", ident(f), ident(f)))
                .collect::<String>()
        ));
        rs.push_str(&format!(
            "impl {id}Any {{\n    /// The item as {name} or the subclass it is.\n    pub fn from_item(item: Item) -> Result<{id}Any> {{\n        match item.class() {{\n{}            other => Err(ubos_sdk::Error::new(\"MODEL.INVALID_VALUE\", format!(\"{{other}} is not a {name}\"), serde_json::json!({{\"class\": other}}))),\n        }}\n    }}\n    /// The item.\n    pub fn item(&self) -> &Item {{\n        match self {{\n{}        }}\n    }}\n}}\n",
            family
                .iter()
                .map(|f| format!("            \"{f}\" => Typed::from_item(item).map({id}Any::{}),\n", ident(f)))
                .collect::<String>(),
            family
                .iter()
                .map(|f| format!("            {id}Any::{}(t) => &t.item,\n", ident(f)))
                .collect::<String>()
        ));
        rs.push_str(&format!(
            "impl {id} {{\n    /// The class name.\n    pub const CLASS: &'static str = \"{name}\";\n    /// One object by slug: {name} or a subclass.\n    pub async fn get(c: &Client, slug: &str, sel: &Selectors) -> Result<{id}Any> {{\n        {id}Any::from_item(ubos_sdk::typed::get(c, \"{name}\", slug, sel).await?)\n    }}\n    /// A query of {name} and its subclasses; run it with `{id}Any::from_item`.\n    pub fn query() -> Query {{\n        Query::new(\"{name}\")\n    }}\n}}\n"
        ));
        if !c.ports.is_empty() {
            rs.push_str(&format!(
                "/// ports of {name}\npub mod {} {{\n    use super::*;\n",
                id.to_lowercase()
            ));
            for (pname, port) in &c.ports {
                let params: Vec<(String, String, String)> = port.decl["params"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .map(|p| {
                        let n = p
                            .get("name")
                            .and_then(Value::as_str)
                            .unwrap_or("arg")
                            .to_string();
                        let t = map_type(
                            p.get("type").and_then(Value::as_str).unwrap_or("text"),
                            "rs",
                            &custom,
                        );
                        let t = if p.get("required") == Some(&Value::Bool(true)) {
                            t
                        } else {
                            format!("Option<{t}>")
                        };
                        (rs_ident(&n), n, t)
                    })
                    .collect();
                rs.push_str(&format!(
                    "    /// {} port `{pname}`, declared by {}\n    pub const {}: &str = \"{pname}\";\n    /// Invoke `{pname}` on an object of {name}.\n    pub async fn {}(c: &Client, target: &str{}, o: &CallOptions) -> Result<MutateResult> {{\n        c.invoke(target, \"{pname}\", serde_json::json!({{{}}}), o).await\n    }}\n",
                    port.decl.get("kind").and_then(Value::as_str).unwrap_or("command"),
                    port.declared_by,
                    ident(pname).to_uppercase(),
                    rs_ident(&ident(pname).to_lowercase()),
                    params.iter().map(|(i, _, t)| format!(", {i}: {t}")).collect::<String>(),
                    params.iter().map(|(i, n, _)| format!("\"{n}\": {i}")).collect::<Vec<_>>().join(", ")
                ));
            }
            rs.push_str("}\n");
        }
        rs.push('\n');
    }
    Ok((ts, rs, header))
}
