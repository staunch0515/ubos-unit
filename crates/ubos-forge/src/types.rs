//! `forge types` (DSN-FRG-102): TypeScript and Rust types for the classes, value types
//! and ports of a project, versioned per branch and model hash (FR-DEV-031, -032).

use crate::project::Project;
use serde_json::Value;
use std::collections::BTreeMap;

/// A field type of the model mapped to the target languages.
fn map_type(t: &str, lang: &str, custom: &BTreeMap<String, Value>) -> String {
    let ts = lang == "ts";
    match t {
        "text" | "enum" | "date" | "instant" | "uuid" | "uri" | "did" => {
            if ts { "string" } else { "String" }.into()
        }
        "integer" => if ts { "number" } else { "i64" }.into(),
        "decimal" => if ts { "string" } else { "String" }.into(),
        "boolean" => if ts { "boolean" } else { "bool" }.into(),
        "money" => "Money".into(),
        "period" => "Period".into(),
        "reference" | "relationship" => if ts { "string" } else { "String" }.into(),
        "list" => if ts {
            "unknown[]"
        } else {
            "Vec<serde_json::Value>"
        }
        .into(),
        "map" | "json" => if ts {
            "Record<string, unknown>"
        } else {
            "serde_json::Value"
        }
        .into(),
        other if custom.contains_key(other) => {
            let base = custom[other]
                .get("base")
                .and_then(Value::as_str)
                .unwrap_or("text");
            map_type(base, lang, &BTreeMap::new())
        }
        _ => if ts { "unknown" } else { "serde_json::Value" }.into(),
    }
}

fn ident(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// Generate `types.ts` and `types.rs`; returns `(typescript, rust, header)`.
pub fn generate(project: &Project) -> Result<(String, String, Value), ubos_dvm::BpaError> {
    let base = ubos_dvm::expressions::registry();
    let decls = project.declarations();
    let vts = project.value_type_decls();
    let reg = base.load(&decls, if vts.is_empty() { None } else { Some(&vts) })?;
    let custom: BTreeMap<String, Value> = reg.value_types().clone();
    let model_hash = project.model_hash()?;
    let header = serde_json::json!({"project": project.manifest.name, "branch": project.manifest.branch,
        "model_hash": model_hash, "abi": project.manifest.abi});
    let banner = format!(
        "generated by forge types; project {} branch {} model {}; do not edit",
        project.manifest.name, project.manifest.branch, model_hash
    );
    let mut ts = format!(
        "// {banner}\n\nexport interface Money {{ amount: string; currency: string }}\nexport interface Period {{ from: string; to: string | null }}\nexport const MODEL_HASH = \"{model_hash}\";\nexport const BRANCH = \"{}\";\n\n",
        project.manifest.branch
    );
    let mut rs = format!(
        "//! {banner}\n#![allow(missing_docs, dead_code, clippy::all)]\n\nuse serde::{{Deserialize, Serialize}};\n\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct Money {{ pub amount: String, pub currency: String }}\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct Period {{ pub from: String, pub to: Option<String> }}\npub const MODEL_HASH: &str = \"{model_hash}\";\npub const BRANCH: &str = \"{}\";\n\n",
        project.manifest.branch
    );
    for (name, vt) in &custom {
        let base_t = vt.get("base").and_then(Value::as_str).unwrap_or("text");
        ts.push_str(&format!(
            "export type {} = {};\n",
            ident(name),
            map_type(base_t, "ts", &BTreeMap::new())
        ));
        rs.push_str(&format!(
            "pub type {} = {};\n",
            ident(name),
            map_type(base_t, "rs", &BTreeMap::new())
        ));
    }
    if !custom.is_empty() {
        ts.push('\n');
        rs.push('\n');
    }
    let mut names: Vec<String> = decls
        .iter()
        .filter_map(|d| d.get("name").and_then(Value::as_str).map(str::to_string))
        .collect();
    names.sort();
    for name in &names {
        let c = reg.class(name)?;
        let parent = c.linearization.get(1).cloned();
        ts.push_str(&format!(
            "/** class {name} (kind {}, version {}) */\nexport interface {}{} {{\n",
            c.kind.clone().unwrap_or_default(),
            c.class_version,
            ident(name),
            parent
                .as_ref()
                .filter(|p| names.contains(p))
                .map(|p| format!(" extends {}", ident(p)))
                .unwrap_or_default()
        ));
        rs.push_str(&format!("/// class {name} (kind {}, version {})\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct {} {{\n", c.kind.clone().unwrap_or_default(), c.class_version, ident(name)));
        let own: Vec<&String> = if let Some(p) = parent.as_ref().filter(|p| names.contains(p)) {
            let pc = reg.class(p)?;
            c.fields
                .keys()
                .filter(|k| !pc.fields.contains_key(*k))
                .collect()
        } else {
            c.fields.keys().collect()
        };
        for f in &c.fields {
            let (fname, decl) = f;
            let t = decl.get("type").and_then(Value::as_str).unwrap_or("text");
            let required = decl.get("required") == Some(&Value::Bool(true));
            if own.contains(&fname) {
                ts.push_str(&format!(
                    "  {}{}: {};\n",
                    ident(fname),
                    if required { "" } else { "?" },
                    map_type(t, "ts", &custom)
                ));
            }
            let rt = map_type(t, "rs", &custom);
            rs.push_str(&format!(
                "    pub {}: {},\n",
                ident(fname),
                if required {
                    rt
                } else {
                    format!("Option<{rt}>")
                }
            ));
        }
        ts.push_str("}\n");
        rs.push_str("}\n");
        if !c.ports.is_empty() {
            ts.push_str(&format!("export interface {}Ports {{\n", ident(name)));
            rs.push_str(&format!(
                "/// ports of {name}\npub mod {} {{\n",
                ident(name).to_lowercase()
            ));
            for (pname, port) in &c.ports {
                let params: Vec<String> = port.decl["params"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .map(|p| {
                        format!(
                            "{}: {}",
                            ident(p.get("name").and_then(Value::as_str).unwrap_or("arg")),
                            map_type(
                                p.get("type").and_then(Value::as_str).unwrap_or("text"),
                                "ts",
                                &custom
                            )
                        )
                    })
                    .collect();
                ts.push_str(&format!(
                    "  /** {} port, declared by {} */\n  {}({}): Promise<unknown>;\n",
                    port.decl
                        .get("kind")
                        .and_then(Value::as_str)
                        .unwrap_or("command"),
                    port.declared_by,
                    ident(pname),
                    params.join(", ")
                ));
                rs.push_str(&format!("    /// {} port `{pname}`, declared by {}\n    pub const {}: &str = \"{pname}\";\n", port.decl.get("kind").and_then(Value::as_str).unwrap_or("command"), port.declared_by, ident(pname).to_uppercase()));
            }
            ts.push_str("}\n");
            rs.push_str("}\n");
        }
        ts.push('\n');
        rs.push('\n');
    }
    Ok((ts, rs, header))
}
